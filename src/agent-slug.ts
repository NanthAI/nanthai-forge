const adjectives = new Set<string>(AGENT_SLUG_ADJECTIVES);
const nouns = new Set<string>(AGENT_SLUG_NOUNS);
const shape = /^([a-z]{2,10})-([a-z]{2,10})$/;

/** The slug for a 64-bit digest of one agent session id (agent-slug-session.ts makes it). */
export const slugFromDigest = (hex: string) =>
  `${AGENT_SLUG_ADJECTIVES[parseInt(hex.slice(0, 8), 16) % AGENT_SLUG_ADJECTIVES.length]}-${AGENT_SLUG_NOUNS[parseInt(hex.slice(8, 16), 16) % AGENT_SLUG_NOUNS.length]}`;

/** A slug made from the fixed lists, so a stored value can name no person, path or secret. */
export function isAgentSlug(value: unknown): value is string {
  if (typeof value !== 'string') return false;
  const match = shape.exec(value);
  return !!match && adjectives.has(match[1]!) && nouns.has(match[2]!);
}

/** The actor value a view returns: `ACCOUNT/slug` for an agent session, the account alone for a
 * person. The public identity wrapper (convex/publicPeople.ts) turns the account into its handle. */
export const agentActor = (actor: string, agent?: string | null) =>
  agent && isAgentSlug(agent) ? `${actor}/${agent}` : actor;

/** Splits `ACCOUNT/slug`; null for any other value (a person, a system actor, a path). */
export function splitAgentActor(value: string): { actor: string; agent: string } | null {
  const at = value.lastIndexOf('/');
  if (at <= 0) return null;
  const agent = value.slice(at + 1);
  return isAgentSlug(agent) ? { actor: value.slice(0, at), agent } : null;
}

/** How a public actor reads in a line: `handle/slug` for an agent, `@handle` for a person. */
export const actorLabel = (actor: string | undefined, fallback = 'a member') =>
  !actor ? fallback : splitAgentActor(actor) ? actor : `@${actor}`;

/** The receipt's agent run (d730121f) from a client-sent slug: anything not from the fixed lists is dropped. */
export const landingAgentRun = (agent: unknown): { agentRun?: string } =>
  isAgentSlug(agent) ? { agentRun: agent } : {};
