export interface ExchangeTransport {
  readonly metadataTrees?: boolean;
  readonly workRecords?: boolean;
  checkpointKey?(backupId?: string): string | undefined;
  missing(objects: ContentPin[]): Promise<string[]>;
  upload(pin: ContentPin, bytes: Buffer): Promise<void | TransferReceipt>;
  uploadBatch?(objects: { pin: ContentPin; bytes: Buffer }[]): Promise<void | TransferReceipt>;
  uploadLazyBatch?(
    objects: { pin: ContentPin; read: () => Buffer | Promise<Buffer> }[],
  ): Promise<TransferReceipt>;
  uploadFile?(pin: ContentPin, root: string, path: string): Promise<TransferReceipt>;
  published?(pin: ContentPin): Promise<string | null>;
  ownerDisplayBaseline?(): Promise<boolean>;
  publishedOwnerDerived?(backupId: string): Promise<ContentPin | null>;
  publish(pin: ContentPin, metadataOnly?: false, ownerDerived?: ContentPin): Promise<string>;
  publishMetadata?(
    pin: ContentPin,
    build: () => PublicationMetadata,
    ownerDerived?: ContentPin,
  ): Promise<string | null>;
  manifest(backupId: string): Promise<{ json: string; digest: string; size: number; sourceDigest?: string }>;
  download(pin: ContentPin): Promise<Buffer>;
  downloadBatch?(pins: ContentPin[]): Promise<Buffer[]>;
  downloadToFile?(pin: ContentPin, path: string): Promise<void>;
}
const coverage =
  'Complete retained native source ancestry, Work records and available recorded run files, transferred as project-scoped immutable objects. Identical source and artifact bytes are reused across checkpoints. Uncheckpointed files, ignored credentials and processes are excluded. Full recovery archives remain an explicit local export.';

// This retry manifest is transport state, never a second Work authority. No source
// or artifact trees are copied and no archive is generated by ordinary exchange.
export async function prepareNativeExchange(
  store: WorkStore,
  revision: number,
  operationId: string,
  incrementalMetadata = false,
  baselineKey?: string,
  ownerDerivedBaselineKey: string | null | undefined = baselineKey,
  options: {
    pinCurrent?: boolean;
    captured?: CapturedExchange;
    recordMetadata?: boolean;
    journalRevision?: number;
  } = {},
) {
  invariant(
    /^[0-9a-f]{8}(-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i.test(operationId),
    'BAD_ARGUMENT',
    'Select an owner and an original exchange UUID.',
  );
  if (!store.native) return prepareGitExchange(store, revision, operationId, incrementalMetadata);
  const directory = join(store.directory, `exchange-${operationId}`),
    manifestPath = join(directory, 'manifest.json');
  if (existsSync(manifestPath)) {
    const json = readFileSync(manifestPath, 'utf8'),
      manifest = nativeManifestSchema.parse(JSON.parse(json));
    // A pinCurrent revision is a floor: the retained snapshot is this operation's
    // only candidate and is never recaptured under the same ID.
    invariant(
      manifest.id === operationId &&
        (options.pinCurrent ? manifest.revision >= revision : manifest.revision === revision),
      'WORK_OPERATION_CHANGED',
      'Reconcile the exchange with its original revision and operation.',
    );
    return { directory, json, manifest, fresh: false };
  }
  const baseline = exchangeBaseline(store, baselineKey);
  // Only the small commit pointer is read under the owner lock. Its records are
  // immutable and retained, so materializing them needs no lock.
  const captured = options.captured ? recoveryTiming(options.captured.directory) : undefined;
  const localCapture = options.captured
    ? undefined
    : store.locked(
        () => {
          const pointer = store.pointer();
          return {
            pointer,
            capturedAt: new Date().toISOString(),
            pending: capturePendingExchange(store.directory, pointer),
          };
        },
        { operation: 'exchange snapshot' },
      );
  const snapshot = (() => {
    // Rollout: hosted still reads schema 15 until the hosted converter lands.
    const data = hostedPushWork(options.captured?.data ?? store.pinnedData(localCapture?.pointer ?? null));
    if (options.pinCurrent)
      invariant(
        data.revision >= revision,
        'WORK_OPERATION_CHANGED',
        'Local Work moved behind the pinned push revision. Existing Work remains preserved.',
      );
    else invariant(data.revision === revision, 'WORK_STALE', 'Work changed before exchange.');
    return { data, bytes: Buffer.from(JSON.stringify(data, null, 2)) };
  })();
  const sizes = new Map<string, number>(
      baseline?.manifest.files
        .filter(pin => pin.path.startsWith('objects/'))
        .map(pin => [pin.sha256, pin.size]),
    ),
    states = new Set<string>(baseline?.states);
  // The pinned Work snapshot references immutable retained source. Network and
  // closure validation need no mutable owner lock; a missing object fails explicitly.
  const ids = nativeReachable(
    store,
    snapshot.data,
    (id, bytes, state) => {
      sizes.set(id, bytes.length);
      if (state) states.add(id);
    },
    sizes.keys(),
    baseline?.states,
  );
  const files: z.infer<typeof nativeFileSchema>[] = [
      { path: 'work.json', size: snapshot.bytes.length, sha256: digest(snapshot.bytes) },
    ],
    unavailable: string[] = [];
  const mutable: Record<string, Buffer> = {};
  const source = new NativeSource(store.root);
  for (const id of ids) {
    const size = sizes.get(id) ?? source.object(id).length;
    files.push({ path: `objects/${id}`, size, sha256: id });
  }
  if (options.captured) {
    const captured = nativeManifestSchema.parse(
      JSON.parse(readFileSync(join(options.captured.directory, 'manifest.json'), 'utf8')),
    );
    files.push(
      ...captured.files.filter(file => file.path !== 'work.json' && !file.path.startsWith('objects/')),
    );
    unavailable.push(...captured.unavailable);
    for (const file of files.filter(file => file.path.startsWith('check-'))) {
      const path = join(options.captured.directory, `pinned-${file.sha256}`);
      if (existsSync(path)) mutable[`pinned-${file.sha256}`] = readFileSync(path);
    }
  }
  for (const run of options.captured ? [] : snapshot.data.runs) {
    const prefix = `check-${run.id}`,
      folder = join(store.directory, prefix);
    if (run.endedAt && baseline?.completedRuns.has(digest(JSON.stringify(run)))) {
      files.push(...baseline.manifest.files.filter(pin => pin.path.startsWith(`${prefix}/`)));
      unavailable.push(...baseline.manifest.unavailable.filter(path => path.startsWith(`${prefix}/`)));
      continue;
    }
    for (const name of [
      'stdout.log',
      'stderr.log',
      ...(run.endedAt ? ['result.json'] : []),
      ...(run.resourceUsage?.producer ? ['resources.txt'] : []),
    ]) {
      const path = `${prefix}/${name}`;
      if (!existsSync(join(store.directory, path))) {
        unavailable.push(path);
        continue;
      }
      if (!run.endedAt) {
        const bytes = readSource(store.directory, path, Number.MAX_SAFE_INTEGER);
        invariant(
          bytes,
          'EXCHANGE_SOURCE_CHANGED',
          'The running check output changed during capture; retry preparation before an exchange is committed.',
        );
        const sha256 = digest(bytes);
        mutable[`pinned-${sha256}`] = bytes;
        files.push({ path, size: bytes.length, sha256 });
      } else files.push({ path, ...(await fingerprintPrivateFile(join(store.directory, path))) });
    }
    try {
      await inspectArtifacts(folder, run);
    } catch {
      unavailable.push(
        ...(run.artifacts ?? []).map(artifact =>
          artifact.status === 'retained' ? `${prefix}/artifacts/${artifact.filename}` : artifact.sourcePath,
        ),
      );
      continue;
    }
    for (const artifact of run.artifacts ?? [])
      if (artifact.status === 'retained')
        files.push({
          path: `${prefix}/artifacts/${artifact.filename}`,
          size: artifact.size,
          sha256: artifact.sha256,
        });
  }
  const manifest = nativeManifestSchema.parse({
    schema: 1,
    kind: 'forge-native-work-backup',
    id: operationId,
    head: snapshot.data.nativeHead,
    revision: snapshot.data.revision,
    files,
    unavailable,
    coverage,
  });
  const json = JSON.stringify(manifest);
  const exchange = incrementalMetadata
    ? buildExchangeRoot(
        Buffer.from(json),
        snapshot.bytes,
        options.recordMetadata
          ? {
              records: true,
              ...(baseline?.data ? { baseline: baseline.data } : {}),
              ...(options.journalRevision === undefined ? {} : { journalRevision: options.journalRevision }),
            }
          : {},
      )
    : undefined;
  const current = new Set(states);
  for (const head of hostSourceHeads(snapshot.data)) {
    const state = source.state(head);
    current.add(head);
    for (const file of state.files) current.add(file.blob);
    if (state.git) current.add(state.git.bundle);
  }
  const derivedBytes = ownerDerivedBytes(
    store,
    snapshot.data,
    ownerDerivedBaselineKey === baselineKey
      ? baseline
      : exchangeBaseline(store, ownerDerivedBaselineKey ?? undefined),
  );
  const pendingCapture = options.captured
    ? readPendingCapture(options.captured.directory)
    : localCapture?.pending;
  commitExchangeDirectory(directory, {
    ...(pendingCapture
      ? {
          'pending-work.json': JSON.stringify({
            ...pendingCapture,
            workRevision: snapshot.data.revision,
            workSha256: digest(snapshot.bytes),
          }),
        }
      : {}),
    'recovery-timing.json': JSON.stringify({
      capturedAt: captured ? captured.capturedAt : localCapture!.capturedAt,
      evidenceCapturedAt: captured?.evidenceCapturedAt ?? new Date().toISOString(),
    }),
    'current.json': JSON.stringify([...current]),
    'states.json': JSON.stringify([...states]),
    'work.json': snapshot.bytes,
    'manifest.json': json,
    ...(derivedBytes ? { 'owner-derived.json': derivedBytes } : {}),
    ...(exchange
      ? { 'exchange.json': exchange.bytes, 'exchange-index.json': JSON.stringify(exchange.index) }
      : {}),
    ...mutable,
  });
  return { directory, json, manifest, fresh: true };
}
function readPendingCapture(directory: string) {
  const path = join(directory, 'pending-work.json');
  if (!existsSync(path)) return undefined; // Older retained captures cannot acknowledge pending work.
  const capture = pendingExchangeCaptureSchema.parse(JSON.parse(readFileSync(path, 'utf8')));
  const manifest = sourceManifestSchema.parse(
    JSON.parse(readFileSync(join(directory, 'manifest.json'), 'utf8')),
  );
  invariant(
    capture.workRevision === manifest.revision &&
      capture.workSha256 === manifest.files.find(file => file.path === 'work.json')?.sha256,
    'WORK_OPERATION_CHANGED',
    'Pending-work coverage differs from its captured Work.',
  );
  return capture;
}
export async function pushNativeExchange(
  store: WorkStore,
  revision: number,
  operationId: string,
  transport: ExchangeTransport,
  options: {
    progress?: ReturnType<typeof hostProgress>;
    stage?: 'current' | 'history';
    ownerDerivedBaselineKey?: string | null;
    workBaselineKey?: string;
    journalRevision?: number;
    /** Pin the current local Work revision (at least `revision`) under the short owner lock. */
    pinCurrent?: boolean;
    captured?: CapturedExchange;
    /** Runs after the snapshot is durably retained and before any network access. */
    onPrepared?: (revision: number) => void;
    /** Bound push must finish source return before acknowledging this capture. */
    deferPendingAcknowledgement?: boolean;
  } = {},
) {
  const prepared = await prepareNativeExchange(
      store,
      revision,
      operationId,
      transport.metadataTrees,
      options.workBaselineKey ?? transport.checkpointKey?.(),
      options.ownerDerivedBaselineKey,
      {
        ...(options.pinCurrent ? { pinCurrent: true } : {}),
        ...(options.captured ? { captured: options.captured } : {}),
        ...(transport.workRecords ? { recordMetadata: true } : {}),
        ...(options.journalRevision === undefined ? {} : { journalRevision: options.journalRevision }),
      },
    ),
    manifestBytes = Buffer.from(prepared.json);
  revision = prepared.manifest.revision;
  options.onPrepared?.(revision);
  const displayBaseline = (await transport.ownerDisplayBaseline?.()) ?? true;
  let derivedBytes = preparedOwnerDerived(prepared.directory);
  if (store.native) {
    let current = false;
    try {
      const value = JSON.parse(derivedBytes?.toString('utf8') ?? 'null');
      current =
        value?.schema === 3 &&
        (!('fresh' in prepared && prepared.fresh) || displayBaseline || value.complete === true);
    } catch {
      /* rebuild disposable metadata */
    }
    if (!current) {
      const bytes = readFileSync(join(prepared.directory, 'work.json'));
      const pin = prepared.manifest.files.find(file => file.path === 'work.json');
      invariant(
        pin && bytes.length === pin.size && digest(bytes) === pin.sha256,
        'WORK_OPERATION_CHANGED',
        'Prepare owner display data from the original pinned Work.',
      );
      derivedBytes = ownerDerivedBytes(store, JSON.parse(bytes.toString('utf8')));
      writeFileSync(join(prepared.directory, 'owner-derived.json'), derivedBytes, { mode: 0o600 });
    }
  }
  const derivedPages = derivedBytes ? ownerDerivedPages(derivedBytes) : undefined;
  const ownerDerived = derivedPages
    ? { sha256: digest(derivedPages.root), size: derivedPages.root.length }
    : undefined;
  const tree = preparedMetadata(prepared.directory, manifestBytes);
  const publishedBytes = tree?.bytes ?? manifestBytes,
    manifestPin = { sha256: digest(publishedBytes), size: publishedBytes.length };
  const unique = new Map(
    prepared.manifest.files
      .filter(file => !tree || file.path !== 'work.json')
      .map(file => [file.sha256, file]),
  );
  let pins = [
    ...new Map(
      [
        ...unique.values(),
        ...(tree ? tree.pins : []),
        { path: 'manifest.json', ...manifestPin },
        ...(ownerDerived ? [{ path: 'owner-derived.json', ...ownerDerived }] : []),
        ...[...(derivedPages?.objects ?? [])].map(([sha256, bytes]) => ({
          path: 'owner-derived-page',
          sha256,
          size: bytes.length,
        })),
      ].map(pin => [pin.sha256, pin]),
    ).values(),
  ];
  if (options.stage === 'current') {
    const current = new Set<string>(
      JSON.parse(readFileSync(join(prepared.directory, 'current.json'), 'utf8')),
    );
    pins = pins.filter(pin => !pin.path.startsWith('objects/') || current.has(pin.sha256));
    pins = pins.filter(pin => !pin.path.startsWith('check-'));
  }
  let uploadedBytes = 0,
    uploadedObjects = 0,
    uploadedLogicalObjects = 0;
  const capture = readPendingCapture(prepared.directory);
  const pendingCoverage = capture
    ? {
        capture,
        completeHistory: options.stage !== 'current',
        unavailable: prepared.manifest.unavailable,
      }
    : undefined;
  const result = (backupId: string) => ({
    recovery: retainRecoveryCapture(store, prepared.directory, manifestPin, {
      kind: 'exchange',
      backupId,
      ...(options.stage ? { completeHistory: 'incomplete' as const } : {}),
    }),
    backupId,
    ...(pendingCoverage ? { pendingCoverage } : {}),
    digest: manifestPin.sha256,
    manifest: manifestPin,
    revision,
    transport: 'objects' as const,
    objects: pins.length,
    uploadedObjects,
    uploadedBytes,
    reusedObjects: pins.length - uploadedLogicalObjects,
    logicalBytes: prepared.manifest.files.reduce((sum, file) => sum + file.size, 0),
    archiveCreated: false,
    ...(ownerDerived ? { ownerDerived } : {}),
  });
  const retainBaseline = (backupId: string) => {
    const baselineKey = transport.checkpointKey?.(backupId);
    if (store.native && baselineKey && prepared.manifest.kind === 'forge-native-work-backup') {
      try {
        const bytes = readFileSync(join(prepared.directory, 'work.json')),
          workPin = prepared.manifest.files.find(pin => pin.path === 'work.json');
        invariant(
          workPin && bytes.length === workPin.size && digest(bytes) === workPin.sha256,
          'WORK_OPERATION_CHANGED',
          'Preparation hint Work differs from its pinned bytes.',
        );
        retainExchangeBaseline(
          store,
          baselineKey,
          prepared.manifest,
          JSON.parse(bytes.toString('utf8')),
          pins,
          JSON.parse(readFileSync(join(prepared.directory, 'states.json'), 'utf8')),
        );
      } catch {
        // Publication has succeeded. A disposable preparation hint is never an
        // additional success condition, and a later push can prepare in full.
      }
    }
  };
  const original = options.stage === 'history' ? null : await transport.published?.(manifestPin);
  if (original) {
    const pinned = transport.publishedOwnerDerived
      ? await transport.publishedOwnerDerived(original)
      : ownerDerived;
    retainBaseline(original);
    if (pendingCoverage && !options.deferPendingAcknowledgement)
      acknowledgePendingExchange(store, pendingCoverage);
    return { ...result(original), ownerDerived: pinned ?? undefined };
  }
  const baseline = exchangeBaseline(store, transport.checkpointKey?.());
  const negotiate = pins.filter(pin => baseline?.objects.get(pin.sha256) !== pin.size);
  const pages: (typeof pins)[] = [];
  for (let offset = 0; offset < negotiate.length; offset += 100)
    pages.push(negotiate.slice(offset, offset + 100));
  options.progress?.phase(
    'negotiating',
    pins.length,
    pins.reduce((sum, pin) => sum + pin.size, 0),
  );
  const missingPages = await mapExchange(pages, 4, async page => {
    const missing = new Set(await transport.missing(page));
    options.progress?.advance(
      page.length,
      page.reduce((sum, pin) => sum + pin.size, 0),
    );
    return missing;
  });
  const missingPins = pages.flatMap((page, index) =>
    page.filter(pin => missingPages[index]!.has(pin.sha256)),
  );
  options.progress?.phase(
    options.stage === 'history' ? 'history backfilling' : 'uploading current source',
    missingPins.length,
    missingPins.reduce((sum, pin) => sum + pin.size, 0),
  );
  await mapExchange(
    pages,
    4,
    async (page, index) => {
      const missing = missingPages[index]!;
      const pending = page.filter(pin => missing.has(pin.sha256));
      const readPin = (pin: (typeof pins)[number]) => {
        const base =
          !store.native || ['work.json', 'manifest.json'].includes(pin.path)
            ? prepared.directory
            : store.directory;
        const staged = `pinned-${pin.sha256}`,
          bytes =
            pin.path === 'owner-derived.json'
              ? derivedPages?.root
              : pin.path === 'manifest.json'
                ? publishedBytes
                : (derivedPages?.objects.get(pin.sha256) ??
                  tree?.read(pin.sha256) ??
                  (existsSync(join(prepared.directory, staged))
                    ? readSource(prepared.directory, staged, pin.size + 1, pin.sha256)
                    : readSource(base, pin.path, pin.size + 1, pin.sha256)));
        invariant(
          bytes && bytes.length === pin.size && digest(bytes) === pin.sha256,
          'EXCHANGE_SOURCE_CHANGED',
          'Pinned exchange bytes changed or are unavailable; the original checkpoint is preserved.',
        );
        return bytes;
      };
      if (transport.uploadLazyBatch) {
        const raw = pending.filter(
          pin =>
            pin.size <= 2 * 1024 * 1024 ||
            ['work.json', 'manifest.json'].includes(pin.path) ||
            pin.path.startsWith('metadata/'),
        );
        if (raw.length) {
          const sent = await transport.uploadLazyBatch(raw.map(pin => ({ pin, read: () => readPin(pin) })));
          uploadedObjects += sent.uploadedObjects;
          uploadedBytes += sent.uploadedBytes;
          uploadedLogicalObjects += sent.uploadedLogicalObjects ?? sent.uploadedObjects;
          options.progress?.advance(
            raw.length,
            raw.reduce((sum, pin) => sum + pin.size, 0),
          );
          const transferred = new Set(raw.map(pin => pin.sha256));
          for (let i = pending.length - 1; i >= 0; i--)
            if (transferred.has(pending[i]!.sha256)) pending.splice(i, 1);
        }
      }
      while (pending.length) {
        const first = pending[0]!;
        if (
          transport.uploadFile &&
          first.size > 2 * 1024 * 1024 &&
          !['work.json', 'manifest.json'].includes(first.path) &&
          !first.path.startsWith('metadata/')
        ) {
          pending.shift();
          const staged = `pinned-${first.sha256}`,
            pinned = existsSync(join(prepared.directory, staged));
          const sent = await transport.uploadFile(
            first,
            pinned || !store.native || first.path.startsWith('owner-derived')
              ? prepared.directory
              : store.directory,
            pinned ? staged : first.path,
          );
          uploadedObjects += sent.uploadedObjects;
          uploadedBytes += sent.uploadedBytes;
          uploadedLogicalObjects += sent.uploadedLogicalObjects ?? sent.uploadedObjects;
          options.progress?.advance(1, first.size);
          continue;
        }
        const batch = [pending.shift()!];
        let bytesInFlight = batch[0]!.size;
        while (
          pending.length &&
          !(transport.uploadFile && pending[0]!.size > 2 * 1024 * 1024) &&
          batch.length < 8 &&
          bytesInFlight + pending[0]!.size <= 16 * 1024 * 1024
        ) {
          const pin = pending.shift()!;
          batch.push(pin);
          bytesInFlight += pin.size;
        }
        const content = batch.map(pin => ({ pin, bytes: readPin(pin) }));
        const sent = transport.uploadBatch
          ? await transport.uploadBatch(content)
          : (
              await mapExchange(
                content,
                8,
                async ({ pin, bytes }) =>
                  (await transport.upload(pin, bytes)) ?? { uploadedObjects: 1, uploadedBytes: bytes.length },
              )
            ).reduce(
              (total, sent) => ({
                uploadedObjects: total.uploadedObjects + sent.uploadedObjects,
                uploadedBytes: total.uploadedBytes + sent.uploadedBytes,
                uploadedLogicalObjects:
                  (total.uploadedLogicalObjects ?? 0) + (sent.uploadedLogicalObjects ?? sent.uploadedObjects),
              }),
              { uploadedObjects: 0, uploadedBytes: 0, uploadedLogicalObjects: 0 },
            );
        uploadedBytes += sent?.uploadedBytes ?? content.reduce((sum, item) => sum + item.bytes.length, 0);
        uploadedObjects += sent?.uploadedObjects ?? content.length;
        uploadedLogicalObjects += sent?.uploadedLogicalObjects ?? sent?.uploadedObjects ?? content.length;
        options.progress?.advance(content.length, bytesInFlight);
      }
    },
    { bytes: 32 * 1024 * 1024, size: page => page.reduce((sum, pin) => sum + pin.size, 0) },
  );
  options.progress?.phase('validating checkpoint');
  const nativeManifest =
    prepared.manifest.kind === 'forge-native-work-backup' ? prepared.manifest : undefined;
  const metadataId =
    nativeManifest && store.native && derivedBytes && !options.stage && transport.publishMetadata
      ? await transport.publishMetadata(
          manifestPin,
          () => nativePublicationMetadata(store, prepared.directory, nativeManifest, pins, derivedBytes),
          ownerDerived,
        )
      : null;
  const backupId = metadataId ?? (await transport.publish(manifestPin, false, ownerDerived));
  retainBaseline(backupId);
  if (pendingCoverage && !options.deferPendingAcknowledgement)
    acknowledgePendingExchange(store, pendingCoverage);
  return result(backupId);
}
export async function pullNativeExchange(
  backupId: string,
  target: string,
  transport: ExchangeTransport,
  options: {
    cacheRoot?: string | undefined;
    journalPath?: string | undefined;
    exportOnly?: boolean;
    beforePublish?: (root: string) => void;
  } = {},
) {
  invariant(
    !existsSync(resolve(target)),
    'RESTORE_TARGET_EXISTS',
    'Choose a fresh destination; existing work remains unchanged.',
  );
  const original = await transport.manifest(backupId),
    bytes = Buffer.from(original.json);
  invariant(
    bytes.length === original.size && digest(bytes) === original.digest,
    'INVALID_WORK_BACKUP',
    'Exchange manifest differs from its original digest.',
  );
  const manifest = sourceManifestSchema.parse(JSON.parse(original.json));
  invariant(
    manifest.files.every(file => safeRelative(file.path)),
    'INVALID_WORK_BACKUP',
    'Exchange paths must be contained.',
  );
  invariant(
    new Set(manifest.files.map(file => file.path)).size === manifest.files.length,
    'INVALID_WORK_BACKUP',
    'Exchange repeats a logical path.',
  );
  const directory = realpathSync(mkdtempSync(join(tmpdir(), 'forge-exchange-')));
  let downloadedBytes = 0,
    reusedBytes = 0;
  try {
    const grouped = new Map<string, typeof manifest.files>();
    for (const file of manifest.files) {
      const group = grouped.get(file.sha256);
      if (group) {
        invariant(
          group[0]!.size === file.size,
          'INVALID_WORK_BACKUP',
          'Identical content has inconsistent sizes.',
        );
        group.push(file);
      } else grouped.set(file.sha256, [file]);
    }
    const pending = [...grouped.values()],
      cache = options.cacheRoot ? new WorkStore(options.cacheRoot) : undefined;
    const batches: (typeof pending)[] = [];
    while (pending.length) {
      const batch = [pending.shift()!];
      let bytesInFlight = batch[0]![0]!.size;
      while (pending.length && batch.length < 8 && bytesInFlight + pending[0]![0]!.size <= 16 * 1024 * 1024) {
        const group = pending.shift()!;
        batch.push(group);
        bytesInFlight += group[0]!.size;
      }
      batches.push(batch);
    }
    await mapExchange(
      batches,
      2,
      async batch => {
        const content = new Map<string, Buffer>(),
          streamed = new Map<string, string>(),
          missing: ContentPin[] = [];
        for (const files of batch) {
          const file = files[0]!,
            sourceFile = files.find(item => item.path.startsWith('objects/'));
          const cached =
            cache && sourceFile
              ? readSource(cache.directory, sourceFile.path, file.size + 1, file.sha256)
              : null;
          if (cached && cached.length === file.size && digest(cached) === file.sha256) {
            content.set(file.sha256, cached);
            reusedBytes += cached.length;
          } else if (transport.downloadToFile && file.size > 2 * 1024 * 1024) {
            const path = join(directory, file.path);
            mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
            await transport.downloadToFile(file, path);
            // A transport optimization does not replace the caller's exact-byte check.
            const observed = await fingerprintPrivateFile(path, 'INVALID_WORK_BACKUP');
            invariant(
              observed.size === file.size && observed.sha256 === file.sha256,
              'INVALID_WORK_BACKUP',
              'Exchange content differs from the manifest.',
            );
            streamed.set(file.sha256, path);
            downloadedBytes += file.size;
          } else missing.push(file);
        }
        if (missing.length) {
          // Settle every transfer before removing staging on failure. A transport
          // may batch small objects; larger content keeps the ranged path.
          const outcomes = transport.downloadBatch
            ? (await transport.downloadBatch(missing)).map(bytes => ({
                status: 'fulfilled' as const,
                value: bytes,
              }))
            : await Promise.allSettled(missing.map(file => transport.download(file)));
          invariant(
            outcomes.length === missing.length,
            'INVALID_WORK_BACKUP',
            'Exchange download omitted requested content.',
          );
          for (const [index, outcome] of outcomes.entries()) {
            if (outcome.status === 'rejected') throw outcome.reason;
            const file = missing[index]!,
              bytes = outcome.value;
            invariant(
              bytes.length === file.size && digest(bytes) === file.sha256,
              'INVALID_WORK_BACKUP',
              'Exchange content differs from the manifest.',
            );
            content.set(file.sha256, bytes);
            downloadedBytes += bytes.length;
          }
        }
        for (const files of batch) {
          const bytes = content.get(files[0]!.sha256),
            staged = streamed.get(files[0]!.sha256);
          for (const member of files) {
            const path = join(directory, member.path);
            mkdirSync(dirname(path), { recursive: true, mode: 0o700 });
            if (staged) {
              if (path !== staged) copyFileSync(staged, path, constants.COPYFILE_EXCL);
            } else writeFileSync(path, bytes!, { flag: 'wx', mode: 0o600 });
          }
          reusedBytes += (files.length - 1) * files[0]!.size;
        }
      },
      { bytes: 32 * 1024 * 1024, size: batch => batch.reduce((sum, files) => sum + files[0]!.size, 0) },
    );

    writeFileSync(join(directory, 'manifest.json'), bytes, { flag: 'wx', mode: 0o600 });
    if (options.journalPath)
      overlayHostedJournal(directory, original.sourceDigest ?? original.digest, options.journalPath);
    if (options.exportOnly) {
      invariant(
        manifest.kind === 'forge-native-work-backup',
        'INVALID_WORK_BACKUP',
        'Proposals require native source.',
      );
      await withValidatedNativeArchive(directory, async () => undefined);
      invariant(
        !existsSync(resolve(target)),
        'RESTORE_TARGET_EXISTS',
        'Choose a fresh proposal destination.',
      );
      renameSync(directory, resolve(target));
      return {
        root: resolve(target),
        backupId,
        digest: original.digest,
        downloadedBytes,
        reusedBytes,
        transport: 'objects' as const,
        exported: true,
      };
    }
    const result =
      manifest.kind === 'forge-native-work-backup'
        ? await restoreNativeExchangeStage(directory, target, options.beforePublish)
        : await restoreWork(directory, target);
    return {
      ...result,
      backupId,
      digest: original.digest,
      downloadedBytes,
      reusedBytes,
      transport: 'objects' as const,
    };
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}
